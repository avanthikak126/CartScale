-- CartScale Migration 002: Addresses & Checkout Flow
-- Run this in your Supabase SQL Editor

-- ============================================
-- 1. Create addresses table
-- ============================================

CREATE TABLE addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    full_name text NOT NULL,
    phone text NOT NULL,
    address_line text NOT NULL,
    city text NOT NULL,
    state text NOT NULL,
    pincode text NOT NULL,
    created_at timestamptz DEFAULT now()
);

CREATE INDEX idx_addresses_user_id ON addresses(user_id);

-- ============================================
-- 2. RLS for addresses
-- ============================================

ALTER TABLE addresses ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own addresses"
ON addresses FOR SELECT
USING (auth.uid() = user_id);

CREATE POLICY "Users can create their own addresses"
ON addresses FOR INSERT
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own addresses"
ON addresses FOR UPDATE
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete their own addresses"
ON addresses FOR DELETE
USING (auth.uid() = user_id);

-- ============================================
-- 3. Add address_id and payment_method to orders
-- ============================================

ALTER TABLE orders ADD COLUMN address_id bigint REFERENCES addresses(id);
ALTER TABLE orders ADD COLUMN payment_method text DEFAULT 'cod';

-- ============================================
-- 4. Replace create_order() RPC
--    Now accepts address_id and payment_method
--    Defaults to NULL / 'cod' for backward compatibility
-- ============================================

CREATE OR REPLACE FUNCTION create_order(
    p_address_id bigint DEFAULT NULL,
    p_payment_method text DEFAULT 'cod'
)
RETURNS json
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_cart_id bigint;
    v_order_id bigint;
    v_total numeric(10,2);
BEGIN
    SELECT id
    INTO v_cart_id
    FROM carts
    WHERE user_id = v_user_id
    FOR UPDATE;

    IF v_cart_id IS NULL THEN
        RAISE EXCEPTION 'Cart not found';
    END IF;

    SELECT COALESCE(SUM(p.price * ci.quantity), 0)
    INTO v_total
    FROM cart_items ci
    JOIN products p ON p.id = ci.product_id
    WHERE ci.cart_id = v_cart_id;

    IF v_total = 0 THEN
        RAISE EXCEPTION 'Cart is empty';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM cart_items ci
        JOIN inventory i ON i.product_id = ci.product_id
        WHERE ci.cart_id = v_cart_id
        AND i.quantity < ci.quantity
    ) THEN
        RAISE EXCEPTION 'Insufficient inventory';
    END IF;

    INSERT INTO orders (user_id, total_amount, address_id, payment_method)
    VALUES (v_user_id, v_total, p_address_id, p_payment_method)
    RETURNING id INTO v_order_id;

    INSERT INTO order_items (order_id, product_id, quantity, price)
    SELECT
        v_order_id,
        ci.product_id,
        ci.quantity,
        p.price
    FROM cart_items ci
    JOIN products p ON p.id = ci.product_id
    WHERE ci.cart_id = v_cart_id;

    UPDATE inventory i
    SET quantity = i.quantity - ci.quantity,
        updated_at = now()
    FROM cart_items ci
    WHERE i.product_id = ci.product_id
    AND ci.cart_id = v_cart_id;

    DELETE FROM cart_items
    WHERE cart_id = v_cart_id;

    RETURN json_build_object(
        'order_id', v_order_id,
        'total_amount', v_total
    );
END;
$$;
