-- 4. RPC Functions
-- ============================================

CREATE OR REPLACE FUNCTION create_order(
    p_address_id bigint DEFAULT NULL,
    p_payment_method text DEFAULT 'cod'
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_cart_id bigint;
    v_order_id bigint;
    v_total numeric(10,2);
BEGIN
    -- 1. Ensure user is authenticated
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Not authenticated';
    END IF;

    -- 2. Validate address belongs to the authenticated user
    IF p_address_id IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM addresses WHERE id = p_address_id AND user_id = v_user_id) THEN
            RAISE EXCEPTION 'Invalid address';
        END IF;
    END IF;

    -- 3. Lock the cart to prevent concurrent checkouts for the same user
    SELECT id INTO v_cart_id FROM carts WHERE user_id = v_user_id FOR UPDATE;

    IF v_cart_id IS NULL THEN
        RAISE EXCEPTION 'Cart not found';
    END IF;

    -- 4. Lock inventory rows predictably to prevent deadlocks and race conditions
    PERFORM 1
    FROM inventory i
    JOIN cart_items ci ON ci.product_id = i.product_id
    WHERE ci.cart_id = v_cart_id
    ORDER BY i.product_id
    FOR UPDATE;

    -- 5. Calculate total amount
    SELECT COALESCE(SUM(p.price * ci.quantity), 0) INTO v_total
    FROM cart_items ci
    JOIN products p ON p.id = ci.product_id
    WHERE ci.cart_id = v_cart_id;

    IF v_total = 0 THEN
        RAISE EXCEPTION 'Cart is empty';
    END IF;

    -- 6. Check inventory availability AND existence
    IF EXISTS (
        SELECT 1 FROM cart_items ci
        LEFT JOIN inventory i ON i.product_id = ci.product_id
        WHERE ci.cart_id = v_cart_id AND (i.product_id IS NULL OR i.quantity < ci.quantity)
    ) THEN
        RAISE EXCEPTION 'Insufficient inventory or missing inventory record';
    END IF;

    -- 7. Insert the new order
    INSERT INTO orders (user_id, total_amount, address_id, payment_method)
    VALUES (v_user_id, v_total, p_address_id, p_payment_method)
    RETURNING id INTO v_order_id;

    -- 8. Insert order items
    INSERT INTO order_items (order_id, product_id, quantity, price)
    SELECT v_order_id, ci.product_id, ci.quantity, p.price
    FROM cart_items ci
    JOIN products p ON p.id = ci.product_id
    WHERE ci.cart_id = v_cart_id;

    -- 9. Deduct inventory
    UPDATE inventory i
    SET quantity = i.quantity - ci.quantity, updated_at = now()
    FROM cart_items ci
    WHERE i.product_id = ci.product_id AND ci.cart_id = v_cart_id;

    -- 10. Clear the user's cart
    DELETE FROM cart_items WHERE cart_id = v_cart_id;

    RETURN json_build_object('order_id', v_order_id, 'total_amount', v_total);
END;
$$;


